"""Generate the single Dart producer replacing 594 duplicated test suites.

No expectations are inferred from implementation. The Python oracle owns them.
Run with --check in CI; use without it after intentional catalogue changes.
"""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / 'tool/contracts/pattern_registry.g.dart'
FAMILIES = ('api', 'navigation', 'ui_theme')


def generate():
    imports, cases = [], []
    for family in FAMILIES:
        models = sorted((ROOT / f'lib/features/{family}_patterns').glob('*/pattern_*/model.dart'))
        if len(models) != 198:
            raise ValueError(f'{family}: expected 198 production models, got {len(models)}')
        for model in models:
            number = model.parent.name.removeprefix('pattern_')
            alias = f'{family}_{number}'
            cls = f'{alias}.Pattern{number}Result'
            special = family == 'api' and number in ('001', '002')
            imports.append(f"import 'package:flutter_application_1/{model.relative_to(ROOT / 'lib')}' as {alias};")
            extra = 'body' if number == '001' else 'echo'
            message = "GET https://example.com → 200" if number == '001' else 'POST https://example.com → 200'
            fields = "{'url': 'https://example.com'}" if number == '001' else "{'title': 'foo'}"
            value = f"{cls}(message: '{message}', statusCode: 200, {extra}: {fields})" if special else f"{cls}(message: 'test')"
            lines = [f"    '{family}/{number}': () async {{", f'      const original = {value};', '      final encoded = original.toJson();', '      return <String, Object?>{', "        'encoded': encoded,", f"        'restored': {cls}.fromJson(encoded).toJson(),"]
            if special:
                lines.append(f"        'defaults': const {cls}(message: 'test').toJson(),")
                lines.append(f"        'missingOptional': {cls}.fromJson({{'message': 'hello'}}).toJson(),")
            else:
                service = model.with_name('service.dart')
                imports.append(f"import 'package:flutter_application_1/{service.relative_to(ROOT / 'lib')}' as {alias}_service;")
                # Assignment enforces the concrete return type during analysis.
                lines.insert(3, f'      final {cls} result = await {alias}_service.Pattern{number}Service().run();')
                lines.append("        'service': result.toJson(),")
            lines += ['      };', '    },']
            cases.append('\n'.join(lines))
    return "// Generated by tool/python/generate_pattern_contracts.py; do not edit.\n// dart format off\n" + '\n'.join(imports) + '\n\nMap<String, Future<Map<String, Object?>> Function()> patternProducers() => {\n' + '\n'.join(cases) + '\n};\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != content:
            raise SystemExit('Pattern producer registry is stale: run tool/python/generate_pattern_contracts.py')
    else:
        TARGET.write_text(content)


if __name__ == '__main__':
    main()
