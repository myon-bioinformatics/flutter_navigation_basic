"""Generate stable public-page emoji identities from the Hub catalogue."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'lib/shared/navigation/page_identities.g.dart'
TOOLS = {
    '/': '🏠', '/hub': '🗺️', '/core/clipboard-shelf': '📋',
    '/tools/time/now-timeline': '🕒', '/tools/location/coordinates': '📍',
    '/tools/media/photo-studio': '🖼️', '/tools/http/request-draft': '🌐',
    '/examples/ui-showcase': '🎨', '/examples/composition-generator': '🎸',
    '/examples/irony-generator': '🥐', '/examples/counter-playground': '👾',
    '/examples/external-integration/mcp': '🕸️',
}
ALIASES = {
    '/tools/location/bounding-box': '/tools/media/photo-studio',
    '/examples/composition-generator/seed': '/examples/composition-generator',
    '/examples/clipboard-workbench': '/core/clipboard-shelf',
    '/examples/external-integration/api': '/tools/http/request-draft',
    '/examples/mock-api': '/tools/http/request-draft',
    **{f'/examples/data-processing-interactions/{i}': f'/screen{i}'
       for i in (171, 172, 173, 174, 175, 183, 184)},
}


def identities():
    screens = json.loads((ROOT / 'assets/screens.json').read_text())['screens']
    return {**TOOLS, **{f"/screen{s.get('screenDataId', s.get('id'))}": s['emoji']
                       for s in screens}}


def generate():
    lines = ['// Generated by python/generate_page_identities.py; do not edit.',
             '// One identity per page; deep-link aliases share their destination.',
             'const pageEmojis = <String, String>{']
    lines += [f"  '{route}': '{emoji}'," for route, emoji in identities().items()]
    lines += ['};', '', 'const pageRouteAliases = <String, String>{']
    lines += [f"  '{alias}': '{route}'," for alias, route in ALIASES.items()]
    lines += ['};', '', 'String canonicalPageRoute(String route) =>',
              '    pageRouteAliases[route] ?? route;', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != content:
            raise SystemExit('Page identities stale: run python/generate_page_identities.py')
    else:
        TARGET.write_text(content)


if __name__ == '__main__':
    main()
