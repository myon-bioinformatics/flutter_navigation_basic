#!/usr/bin/env python3
"""Generate test/features/catalogue_smoke_patterns/pattern_catalogue_smoke_test.dart (stdlib only).

One Dart test file replaces the former per-pattern template tests in
api_patterns / navigation_patterns / ui_theme_patterns. For every pattern it
checks the model toJson/fromJson round trip, and runs every service.run()
concurrently per family (each placeholder service waits 100 ms).

Patterns that keep a dedicated test file under test/features/<family>/ are
still round-tripped here but their service is not run (it may do network I/O).

  python3 python/generate_pattern_smoke_test.py          # write
  python3 python/generate_pattern_smoke_test.py --check  # CI: fail if stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FAMILIES = ("api_patterns", "navigation_patterns", "ui_theme_patterns")
OUT = ROOT / "test" / "features" / "catalogue_smoke_patterns" / "pattern_catalogue_smoke_test.dart"  # *_patterns: stays inside the catalogue boundary
PACKAGE = "flutter_application_1"


def patterns(root: Path = ROOT):
    """(family, bucket, number, has_dedicated_test) for every pattern with model+service."""
    found = []
    for family in FAMILIES:
        for model in sorted((root / "lib" / "features" / family).glob("pattern_*/pattern_*/model.dart")):
            folder = model.parent
            if not (folder / "service.dart").exists():
                continue
            number = folder.name.split("_")[1]
            dedicated = (root / "test" / "features" / family / folder.parent.name / f"{folder.name}_test.dart").exists()
            found.append((family, folder.parent.name, number, dedicated))
    return found


def render(found) -> str:
    lines = [
        "// GENERATED by python/generate_pattern_smoke_test.py. Do not edit by hand.",
        "// Regenerate after adding or removing a pattern; CI runs --check.",
        "import 'package:flutter_test/flutter_test.dart';",
        "",
    ]
    for family, bucket, number, dedicated in found:
        alias = f"{family.split('_')[0]}{number}"
        base = f"package:{PACKAGE}/features/{family}/{bucket}/pattern_{number}"
        lines.append(f"import '{base}/model.dart' as {alias}m;")
        if not dedicated:
            lines.append(f"import '{base}/service.dart' as {alias}s;")
    lines += [
        "",
        "class _Pattern {",
        "  const _Pattern(this.id, this.roundTrip, this.run);",
        "  final String id;",
        "  final String Function() roundTrip;",
        "  final Future<String> Function()? run;",
        "}",
        "",
        "// Wait for every service and retain failures in catalogue order.",
        "Future<List<String>> _serviceFailures(List<_Pattern> patterns) async {",
        "  final outcomes = await Future.wait(patterns.map((pattern) async {",
        "    try {",
        "      final message = await pattern.run!();",
        "      return message.isEmpty ? '${pattern.id}: empty message' : null;",
        "    } catch (error, stack) {",
        "      return '${pattern.id}: ${error.runtimeType}: $error\\n$stack';",
        "    }",
        "  }));",
        "  return outcomes.whereType<String>().toList();",
        "}",
        "",
        "final _patterns = <String, List<_Pattern>>{",
    ]
    for family in FAMILIES:
        lines.append(f"  '{family}': [")
        for fam, _, number, dedicated in found:
            if fam != family:
                continue
            alias = f"{family.split('_')[0]}{number}"
            cls = f"Pattern{number}Result"
            run = "null" if dedicated else (
                f"() async => (await {alias}s.Pattern{number}Service().run()).message")
            lines.append(
                f"    _Pattern('{family}/pattern_{number}', () {{ "
                f"final json = const {alias}m.{cls}(message: 'test').toJson(); "
                f"if (json['message'] != 'test') return 'toJson lost message'; "
                f"return {alias}m.{cls}.fromJson(json).message; }}, {run}),")
        lines.append("  ],")
    lines += [
        "};",
        "",
        "void main() {",
        "  test('service diagnostics retain every failing ID and exception', () async {",
        "    var completed = false;",
        "    final failed = await _serviceFailures([",
        "      _Pattern('sentinel/sync', () => 'test', () => throw StateError('sync failure')),",
        "      _Pattern('sentinel/async', () => 'test', () async {",
        "        await Future<void>.delayed(Duration.zero);",
        "        throw ArgumentError('async failure');",
        "      }),",
        "      _Pattern('sentinel/empty', () => 'test', () async => ''),",
        "      _Pattern('sentinel/success', () => 'test', () async {",
        "        await Future<void>.delayed(Duration.zero);",
        "        completed = true;",
        "        return 'ok';",
        "      }),",
        "    ]);",
        "    expect(completed, isTrue);",
        "    expect(failed, hasLength(3));",
        "    expect(failed[0], contains('sentinel/sync: StateError: Bad state: sync failure'));",
        "    expect(failed[1], contains('sentinel/async: ArgumentError: Invalid argument(s): async failure'));",
        "    expect(failed[2], equals('sentinel/empty: empty message'));",
        "  });",
        "",
        "  for (final entry in _patterns.entries) {",
        "    group(entry.key, () {",
        "      for (final pattern in entry.value) {",
        "        test('${pattern.id}: model toJson and fromJson', () {",
        "          expect(pattern.roundTrip(), equals('test'));",
        "        });",
        "      }",
        "",
        "      test('every service.run() completes with a non-empty message', () async {",
        "        final runnable = entry.value.where((p) => p.run != null).toList();",
        "        final failed = await _serviceFailures(runnable);",
        "        expect(failed, isEmpty, reason: failed.join('\\n'));",
        "        expect(runnable, isNotEmpty);",
        "      });",
        "    });",
        "  }",
        "}",
    ]
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the committed file is stale")
    args = parser.parse_args(argv)
    text = render(patterns())
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is stale; run {Path(__file__).relative_to(ROOT)}", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
